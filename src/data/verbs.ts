// Enrich verbs with auto-generated complete conjugations
export const VERBS_DATABASE: VerbItem[] = RAW_VERBS.map(seed => {
  const conjugations = generateConjugations(
    seed.kanji,
    seed.reading,
    seed.group,
    seed.subgroup,
    seed.isException
  );

  return {
    ...seed,
    conjugations,
  };
});

/**
 * Find verb by search query (kanji, reading, or romaji)
 */
export function searchVerb(query: string): VerbItem | undefined {
  const q = query.trim().toLowerCase();
  if (!q) return undefined;
  return VERBS_DATABASE.find(
    v =>
      v.kanji === q ||
      v.reading === q ||
      v.romaji.toLowerCase() === q ||
      v.meaning.includes(q)
  );
}
